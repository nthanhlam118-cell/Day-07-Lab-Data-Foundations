import os
import sys
from pathlib import Path

sys.path.append(os.path.abspath('.'))

from src.models import Document
from src.chunking import RecursiveChunker
from src.store import EmbeddingStore
from src.agent import KnowledgeBaseAgent

files_metadata = [
    ("data/do_retrieval_best_practices.md", {"category": "retrieval", "doc_type": "concept"}),
    ("data/do_chunking_best_practices.md", {"category": "chunking", "doc_type": "concept"}),
    ("data/do_system_instructions_best_practices.md", {"category": "prompting", "doc_type": "concept"}),
    ("data/do_create_knowledge_bases.md", {"category": "setup", "doc_type": "how_to"}),
    ("data/do_test_knowledge_bases.md", {"category": "evaluation", "doc_type": "how_to"})
]

docs = []
for filepath, meta in files_metadata:
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()
    
    print(f"File: {filepath} | Chars: {len(content)}")
    
    chunker = RecursiveChunker(chunk_size=700)
    chunks = chunker.chunk(content)
    
    for i, c in enumerate(chunks):
        docs.append(Document(
            id=f"{Path(filepath).stem}_chunk{i}",
            content=c,
            metadata={**meta, "source": "DigitalOcean Docs"}
        ))

store = EmbeddingStore(collection_name="lam_benchmark")
store.add_documents(docs)

queries = [
    "What are DigitalOcean's recommended best practices for a strong retrieval setup?",
    "Why can chunks that are too small or too large hurt retrieval quality?",
    "When should filters be used in knowledge base retrieval?",
    "What is the difference between chunking, retrieval, and reranking in a RAG system?",
    "How should a team test whether a knowledge base returns useful answers?"
]

def mock_llm(prompt):
    return f"Mock answer generated by agent"

agent = KnowledgeBaseAgent(store=store, llm_fn=mock_llm)

print("\n--- BENCHMARK RESULTS ---")
for i, q in enumerate(queries, 1):
    print(f"\nQuery {i}: {q}")
    results = store.search(q, top_k=3)
    for j, r in enumerate(results, 1):
        content_preview = r['content'][:150].replace('\n', ' ')
        print(f"  Top-{j} | Score: {r['score']:.4f} | Chunk ID: {r['id']} | Content: {content_preview}...")
    
    ans = agent.answer(q)
    print(f"  Agent Answer: {ans}")
